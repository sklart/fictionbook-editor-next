        var textA = getTextContent(elementA);
        textA = normalizeSpaces(textA);
        textA = trimEnd(textA);
        if (textA.length < 2) return false;
        // Ищем последний значимый символ ПЕРЕД кавычкой
        var foundQuote = false;
