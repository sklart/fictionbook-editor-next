    // 0 - не ищем, 1 - ищем, по умолчанию 1 - ищем
    var searchSquareTilde = 1;

    // Маркеры {~1~}:
    // 0 - не ищем, 1 - ищем, по умолчанию 1 - ищем
    var searchCurlyTilde = 1;

